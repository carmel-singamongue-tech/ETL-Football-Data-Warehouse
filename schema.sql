CREATE SCHEMA IF NOT EXISTS dw_football;

-- Dimension des clubs
CREATE TABLE IF NOT EXISTS dw_football.dim_club (
    club_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_club VARCHAR(10) NOT NULL UNIQUE,
    nom_club VARCHAR(100) NOT NULL
);

-- Dimension des saisons
CREATE TABLE IF NOT EXISTS dw_football.dim_saison (
    saison_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle_saison VARCHAR(9) NOT NULL UNIQUE,
    annee_debut INTEGER NOT NULL,
    annee_fin INTEGER NOT NULL,
    CONSTRAINT ck_dim_saison_annees
        CHECK (annee_fin = annee_debut + 1)
);

-- Dimension des stades
CREATE TABLE IF NOT EXISTS dw_football.dim_stade (
    stade_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_stade VARCHAR(10) NOT NULL UNIQUE,
    nom_stade VARCHAR(150) NOT NULL
);

-- Table de faits : une ligne par club et par match
-- Chaque match produit deux lignes : domicile et extérieur.
-- Les spectateurs et recettes sont enregistrés uniquement
-- sur la ligne du club à domicile afin d'éviter le double comptage.
CREATE TABLE IF NOT EXISTS dw_football.fait_match (
    fait_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_match VARCHAR(20) NOT NULL,
    club_key BIGINT NOT NULL,
    club_adverse_key BIGINT NOT NULL,
    saison_key BIGINT NOT NULL,
    stade_key BIGINT NOT NULL,
    role_club VARCHAR(12) NOT NULL,
    buts_marques INTEGER NOT NULL DEFAULT 0,
    buts_encaisses INTEGER NOT NULL DEFAULT 0,
    victoires INTEGER NOT NULL DEFAULT 0,
    nuls INTEGER NOT NULL DEFAULT 0,
    defaites INTEGER NOT NULL DEFAULT 0,
    spectateurs INTEGER NOT NULL DEFAULT 0,
    recette NUMERIC(14,2) NOT NULL DEFAULT 0,

    CONSTRAINT fk_fait_club
        FOREIGN KEY (club_key)
        REFERENCES dw_football.dim_club (club_key),

    CONSTRAINT fk_fait_club_adverse
        FOREIGN KEY (club_adverse_key)
        REFERENCES dw_football.dim_club (club_key),

    CONSTRAINT fk_fait_saison
        FOREIGN KEY (saison_key)
        REFERENCES dw_football.dim_saison (saison_key),

    CONSTRAINT fk_fait_stade
        FOREIGN KEY (stade_key)
        REFERENCES dw_football.dim_stade (stade_key),

    CONSTRAINT uq_fait_match_club
        UNIQUE (id_match, club_key),

    CONSTRAINT ck_fait_role
        CHECK (role_club IN ('DOMICILE', 'EXTERIEUR')),

    CONSTRAINT ck_fait_mesures_non_negatives
        CHECK (
            buts_marques >= 0
            AND buts_encaisses >= 0
            AND victoires >= 0
            AND nuls >= 0
            AND defaites >= 0
            AND spectateurs >= 0
            AND recette >= 0
        ),

    CONSTRAINT ck_fait_resultat_unique
        CHECK (victoires + nuls + defaites = 1),

    CONSTRAINT ck_fait_clubs_differents
        CHECK (club_key <> club_adverse_key),

    CONSTRAINT ck_fait_recette_domicile
        CHECK (
            role_club = 'DOMICILE'
            OR (spectateurs = 0 AND recette = 0)
        )
);

-- Index utiles pour les jointures et analyses
CREATE INDEX IF NOT EXISTS idx_fait_club
    ON dw_football.fait_match (club_key);

CREATE INDEX IF NOT EXISTS idx_fait_saison
    ON dw_football.fait_match (saison_key);

CREATE INDEX IF NOT EXISTS idx_fait_stade
    ON dw_football.fait_match (stade_key);

-- Fin du script.
-- Remarque : IF NOT EXISTS ne modifie pas une table déjà créée.
